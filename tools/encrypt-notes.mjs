// Encrypts private speaker notes for /deck so they can live in this public repo.
// Usage: DECK_PASSWORD='...' node tools/encrypt-notes.mjs path/to/notes.json > deck/notes.enc.js
// Keep notes.json out of the repo.
import { readFileSync } from 'node:fs';
import { webcrypto as crypto } from 'node:crypto';

const pw = process.env.DECK_PASSWORD;
const file = process.argv[2];
if (!pw || !file) { console.error('Set DECK_PASSWORD and pass the notes.json path.'); process.exit(1); }

const plain = JSON.stringify(JSON.parse(readFileSync(file, 'utf8')));
const iter = 250000;
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const base = await crypto.subtle.importKey('raw', new TextEncoder().encode(pw), 'PBKDF2', false, ['deriveKey']);
const key = await crypto.subtle.deriveKey({ name: 'PBKDF2', salt, iterations: iter, hash: 'SHA-256' }, base, { name: 'AES-GCM', length: 256 }, false, ['encrypt']);
const data = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, new TextEncoder().encode(plain)));
const b64 = (u) => Buffer.from(u).toString('base64');

process.stdout.write('// Encrypted speaker notes. Generated by tools/encrypt-notes.mjs, do not edit by hand.\n' +
  'window.DECK_NOTES_ENC = ' + JSON.stringify({ iter, salt: b64(salt), iv: b64(iv), data: b64(data) }) + ';\n');
